export function searchSymbols(query: string, limit = 12): string[] {
  const q = query.trim().toUpperCase();
  if (!q) return [];
  const matches: Array<{ sym: string; score: number }> = [];
  const seen = new Set<string>();
  for (const sym of TOP_SYMBOLS) {
    if (seen.has(sym)) continue;
    seen.add(sym);
    const name = (SYMBOL_NAMES[sym] ?? '').toUpperCase();
    let score = 0;
    if (sym === q) score = 100;
    else if (sym.startsWith(q)) score = 80 - (sym.length - q.length);
    else if (sym.includes(q)) score = 50;
    else if (name.includes(q)) score = 40;
    if (score > 0) matches.push({ sym, score });
  }
  return matches
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((m) => m.sym);
}
